import type { AnalyzeResponse } from "@/app/api/analyze/route";
import type { CheckInStatement } from "@/lib/checkin/types";
import styles from "./AnalysisReview.module.css";

interface Props {
  result: AnalyzeResponse;
  statements: CheckInStatement[];
}

const CLAIM_TYPE_LABELS: Record<string, string> = {
  ownership_responsibility: "Ownership",
  decision: "Decision",
  quantitative_event: "Quantitative",
  other: "Other",
};

export default function AnalysisReview({ result, statements }: Props) {
  const { analysis, claims, date } = result;
  const textOf = (order: number) =>
    statements.find((s) => s.statement_order === order)?.statement_text ?? "";

  return (
    <div className={styles.review}>
      <p className={styles.banner}>
        Draft for review. Generated by {result.model}; nothing here is saved or approved.
      </p>

      <section>
        <h2>Standup notes</h2>
        <div className={styles.standup}>
          <BulletList title="Completed" items={analysis.standup.completed} />
          <BulletList title="Struggling" items={analysis.standup.struggling} />
          <BulletList title="Next" items={analysis.standup.next} />
        </div>
      </section>

      <section>
        <h2>Daily reflection · {date}</h2>
        <p>{analysis.summary}</p>
      </section>

      <section>
        <h2>Interview story candidate</h2>
        {analysis.star_candidate ? (
          <dl className={styles.star}>
            <dt>Situation</dt>
            <dd>{analysis.star_candidate.situation}</dd>
            <dt>Task</dt>
            <dd>{analysis.star_candidate.task}</dd>
            <dt>Action</dt>
            <dd>{analysis.star_candidate.action}</dd>
            <dt>Result</dt>
            <dd>{analysis.star_candidate.result}</dd>
            <dt>Learning</dt>
            <dd>{analysis.star_candidate.learning}</dd>
          </dl>
        ) : (
          <p className={styles.muted}>No story candidate for this check-in.</p>
        )}
      </section>

      <section>
        <h2>Claims ({claims.length})</h2>
        {claims.length === 0 && <p className={styles.muted}>No claims extracted.</p>}
        <ol className={styles.claims}>
          {claims.map((c, i) => (
            <li key={i} className={styles.claim}>
              <div className={styles.claimHeader}>
                <strong>{c.claim_text}</strong>
                <span className={c.status === "supported" ? styles.supported : styles.unresolved}>
                  {c.status}
                </span>
              </div>
              <div className={styles.claimMeta}>
                <span>{CLAIM_TYPE_LABELS[c.claim_type]}</span>
                <span>Actors: {c.actors.length ? c.actors.join(", ") : "none"}</span>
                {c.creation_method === "user_designated" && <span>User-designated</span>}
              </div>
              {c.evidence_statement_orders.map((order) => (
                <blockquote key={order} className={styles.evidence}>
                  <span>#{order}</span> {textOf(order)}
                </blockquote>
              ))}
              {c.flags.map((f) => (
                <p key={f} className={styles.flag}>
                  ⚠ {f}
                </p>
              ))}
            </li>
          ))}
        </ol>
      </section>

      {analysis.clarifications_needed.length > 0 && (
        <section>
          <h2>Needs your clarification</h2>
          <ul>
            {analysis.clarifications_needed.map((q, i) => (
              <li key={i}>
                {q.question}
                {q.statement_orders.length > 0 && (
                  <span className={styles.muted}>
                    {" "}
                    (#{q.statement_orders.join(", #")})
                  </span>
                )}
              </li>
            ))}
          </ul>
          <p className={styles.muted}>Answering these comes in Milestone 3.</p>
        </section>
      )}

      <details className={styles.raw}>
        <summary>Raw model output (validated JSON)</summary>
        <pre>{JSON.stringify(analysis, null, 2)}</pre>
      </details>
    </div>
  );
}

function BulletList({ title, items }: { title: string; items: string[] }) {
  return (
    <div>
      <h3>{title}</h3>
      {items.length === 0 ? (
        <p className={styles.muted}>—</p>
      ) : (
        <ul>
          {items.map((item, i) => (
            <li key={i}>{item}</li>
          ))}
        </ul>
      )}
    </div>
  );
}
